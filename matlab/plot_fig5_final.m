%% plot_fig5_final_corrected.m
% Directly runnable MATLAB R2024b script.
%
% FINAL CORRECTED FIG. 5
% ------------------------------------------------------------
% This script uses the THREE frozen manuscript ensembles stored
% losslessly in MainResults/matlab/data/main_results.mat:
%
%   d.run30   -> analysis_runs/main_30
%   d.run50   -> analysis_runs/sensitivity_50
%   d.run100  -> analysis_runs/sensitivity_100
%
% IMPORTANT:
%   d.rankings(:,:,1:3) are NOT N=30/50/100.
%   They are the N=100 ranking matrices for:
%       (:,:,1) total reported
%       (:,:,2) GD reported
%       (:,:,3) GX reported
%
% Therefore all ensemble-size comparisons below are reconstructed directly
% from d.run30.values, d.run50.values, and d.run100.values.
%
% Panels:
%   a  N=100 total-reported pairwise ranking matrix
%   b  All 36 unordered pairs: robustness at N=30/50/100
%   c  N=100 effect separation and ranking consistency (aligned lollipops)
%   d  Nested-ensemble sensitivity of four decision-relevant criteria
%
% Outputs:
%   <current working directory>\Fig5\Fig5_a.fig/.png
%   <current working directory>\Fig5\Fig5_b.fig/.png
%   <current working directory>\Fig5\Fig5_c.fig/.png
%   <current working directory>\Fig5\Fig5_d.fig/.png

clearvars;
close all;
clc;

%% ------------------------------------------------------------------------
% Load frozen manuscript snapshot
% -------------------------------------------------------------------------
d = mr.load_data();
s = mr.style();

sizes = [30 50 100];

r30  = d.run30;
r50  = d.run50;
r100 = d.run100;

if size(r30.values,1) ~= 30 || size(r50.values,1) ~= 50 || size(r100.values,1) ~= 100
    error('Fig5:RunSizeMismatch', ...
        'Expected run30/run50/run100 to contain 30/50/100 members.');
end

if isstring(d.strategies)
    strategyNames = cellstr(d.strategies(:));
elseif iscell(d.strategies)
    strategyNames = d.strategies(:);
else
    strategyNames = cellstr(string(d.strategies(:)));
end

nStrategies = numel(strategyNames);

if nStrategies ~= 9
    error('Fig5:StrategyCount','Expected 9 strategies, found %d.',nStrategies);
end

%% ------------------------------------------------------------------------
% Reconstruct the THREE total-reported ranking matrices correctly
% -------------------------------------------------------------------------
R30  = pairwise_total_reported_local(r30.values);
R50  = pairwise_total_reported_local(r50.values);
R100 = pairwise_total_reported_local(r100.values);

rankByN = cat(3,R30,R50,R100);

% The saved d.rankings object is N=100 total/GD/GX, NOT 30/50/100.
% Verify that its first slice matches our independently reconstructed
% N=100 total-reported matrix exactly.
savedTotal100 = double(d.rankings(:,:,1));

if max(abs(savedTotal100(:)-R100(:))) > 1e-12
    error('Fig5:RankingMismatch', ...
        'Reconstructed N=100 total-reported ranking matrix differs from d.rankings(:,:,1).');
end

%% ------------------------------------------------------------------------
% Build all 36 unordered pair summaries
% -------------------------------------------------------------------------
nPairs = nStrategies*(nStrategies-1)/2;

pairI = zeros(nPairs,1);
pairJ = zeros(nPairs,1);
pairLabels = cell(nPairs,1);
robustness = zeros(nPairs,3);
medianDelta100 = zeros(nPairs,1);
medianAbsEffect100 = zeros(nPairs,1);

E100 = squeeze(r100.values(:,:,1,5))/1000;  % total reported, 10^3 cases

q = 0;

for i = 1:(nStrategies-1)
    for j = (i+1):nStrategies

        q = q + 1;

        pairI(q) = i;
        pairJ(q) = j;
        pairLabels{q} = [strategyNames{i} '-' strategyNames{j}];

        for kk = 1:3
            p = rankByN(i,j,kk);
            robustness(q,kk) = max(p,1-p);
        end

        delta100 = E100(:,i)-E100(:,j);

        medianDelta100(q) = median(delta100,'omitnan');
        medianAbsEffect100(q) = abs(medianDelta100(q));
    end
end

%% ------------------------------------------------------------------------
% Hard integrity checks for the manuscript's frozen main findings
% -------------------------------------------------------------------------
unanimousCounts = zeros(1,3);

for kk = 1:3
    unanimousCounts(kk) = count_unanimous_pairs_local(rankByN(:,:,kk));
end

if ~isequal(unanimousCounts,[6 6 4])
    error('Fig5:UnanimousCountMismatch', ...
        'Expected unanimous pair counts [6 6 4], found [%d %d %d].', ...
        unanimousCounts(1),unanimousCounts(2),unanimousCounts(3));
end

hhllCounts = [ ...
    sum(r30.values(:,6,1,5)  > r30.values(:,9,1,5)), ...
    sum(r50.values(:,6,1,5)  > r50.values(:,9,1,5)), ...
    sum(r100.values(:,6,1,5) > r100.values(:,9,1,5))];

if ~isequal(hhllCounts,[30 50 100])
    error('Fig5:HHLLMismatch', ...
        'Expected HH > LL counts [30 50 100], found [%d %d %d].', ...
        hhllCounts(1),hhllCounts(2),hhllCounts(3));
end

pairs100 = unanimous_pair_labels_local(R100,strategyNames);
expectedPairs100 = sort({'NN-LL','NH-LL','HH-LL','LH-LL'});

if ~isequal(sort(pairs100),expectedPairs100)
    error('Fig5:UnanimousPairIdentityMismatch', ...
        'The N=100 unanimous strategy pairs do not match the frozen manuscript result.');
end

% Cross-check the three existing robustness summaries against the frozen
% expected_robustness object in main_results.mat.
reportedCounts = zeros(11,3);

for kk = 1:3
    n = sizes(kk);
    reportedCounts(:,kk) = mr.robustness(d,n,1);

    if ~isequal(reportedCounts(:,kk),d.expected_robustness(:,kk,1))
        error('Fig5:RobustnessMismatch', ...
            'mr.robustness(d,%d,1) differs from expected_robustness.',n);
    end
end

%% ------------------------------------------------------------------------
% Four selected sensitivity criteria for panel d
% -------------------------------------------------------------------------
criterionNames = { ...
    'HH > LL', ...
    'LL harms both regions', ...
    'HH win-win', ...
    'Unanimously ordered pairs'};

criterionFrac = zeros(4,3);

for kk = 1:3

    n = sizes(kk);

    criterionFrac(1,kk) = reportedCounts(1,kk)/n;
    criterionFrac(2,kk) = reportedCounts(3,kk)/n;
    criterionFrac(3,kk) = reportedCounts(4,kk)/n;
    criterionFrac(4,kk) = unanimousCounts(kk)/36;
end

%% ------------------------------------------------------------------------
% Shared style
% -------------------------------------------------------------------------
INK      = [0.08 0.13 0.17];
SUBINK   = [0.35 0.39 0.42];
GRIDC    = [0.82 0.84 0.85];

if isfield(s,'benefit')
    TEAL = s.benefit;
else
    TEAL = [0.10 0.60 0.63];
end

if isfield(s,'navy')
    NAVY = s.navy;
else
    NAVY = [0.10 0.27 0.43];
end

if isfield(s,'harm')
    HARM = s.harm;
else
    HARM = [0.80 0.58 0.25];
end

SLATE = [0.48 0.60 0.69];

OTHER = darken_local(HARM,0.10);
UNAN  = darken_local(TEAL,0.06);
BEST  = darken_local(NAVY,0.02);

%% ------------------------------------------------------------------------
% Output folder
% -------------------------------------------------------------------------
output_dir = fullfile(pwd,'Fig5');

if ~exist(output_dir,'dir')
    mkdir(output_dir);
end

%% =========================================================================
% PANEL a — N=100 total-reported pairwise ranking matrix
% =========================================================================
figA = figure( ...
    'Color','w', ...
    'Units','pixels', ...
    'Position',[100 40 1050 960], ...
    'Name','Fig5_a', ...
    'NumberTitle','off');

set(figA,'Renderer','painters');

annotation(figA,'textbox',[0.020 0.945 0.040 0.040], ...
    'String','a', ...
    'EdgeColor','none', ...
    'FontName','Arial', ...
    'FontSize',30, ...
    'FontWeight','bold', ...
    'Color','k');

axA = axes(figA,'Position',[0.155 0.215 0.625 0.650]);

imagesc(axA,R100);
axis(axA,'image');

colormap(axA,s.fraction);
clim(axA,[0 1]);

set(axA, ...
    'YDir','reverse', ...
    'FontName','Arial', ...
    'FontSize',16, ...
    'LineWidth',1.0, ...
    'TickDir','out', ...
    'Box','off', ...
    'XColor',INK, ...
    'YColor',INK);

xticks(axA,1:nStrategies);
xticklabels(axA,strategyNames);
xtickangle(axA,90);

yticks(axA,1:nStrategies);
yticklabels(axA,strategyNames);

xlabel(axA,'Strategy B','FontSize',19,'Color',INK);
ylabel(axA,'Strategy A','FontSize',19,'Color',INK);

hold(axA,'on');

for i = 1:nStrategies
    for j = 1:nStrategies

        val = R100(i,j);

        if val > 0.65
            txtColor = [1 1 1];
        else
            txtColor = INK;
        end

        text(axA,j,i,sprintf('%d',round(100*val)), ...
            'HorizontalAlignment','center', ...
            'VerticalAlignment','middle', ...
            'FontName','Arial', ...
            'FontSize',16.2, ...
            'Color',txtColor);

        if i ~= j && (val <= 1e-12 || val >= 1-1e-12)
            rectangle(axA, ...
                'Position',[j-0.48 i-0.48 0.96 0.96], ...
                'EdgeColor',NAVY, ...
                'LineWidth',1.45);
        end
    end
end

annotation(figA,'textbox',[0.18 0.895 0.58 0.030], ...
    'String','Cell value = fraction of the 100-solution ensemble in which strategy A yields fewer reported cases than strategy B', ...
    'EdgeColor','none', ...
    'HorizontalAlignment','center', ...
    'FontName','Arial', ...
    'FontSize',13.0, ...
    'Color',SUBINK);

cbA = colorbar(axA,'southoutside');
cbA.Position = [0.195 0.115 0.545 0.020];
cbA.Ticks = [0 0.5 1];
cbA.TickLabels = {'0','0.5','1'};
cbA.FontName = 'Arial';
cbA.FontSize = 12;
cbA.Color = INK;
cbA.Label.String = 'Fraction with A fewer cases than B';
cbA.Label.FontSize = 14;
cbA.Label.Color = INK;

save_panel_local(figA,output_dir,'Fig5_a');

%% =========================================================================
% PANEL b — robustness across the N=30,50,100 frozen ensembles
% =========================================================================
% Sort by N=100 robustness, then N=50, then N=30.
sortKey = [-robustness(:,3), -robustness(:,2), -robustness(:,1)];
[~,ordB] = sortrows(sortKey,[1 2 3]);

pairLabels_B = pairLabels(ordB);
robustness_B = robustness(ordB,:);

figB = figure( ...
    'Color','w', ...
    'Units','pixels', ...
    'Position',[110 25 1300 1340], ...
    'Name','Fig5_b', ...
    'NumberTitle','off');

