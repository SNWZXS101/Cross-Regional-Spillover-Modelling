        'LineWidth',0.95, ...
        'HandleVisibility','off');

    if isHHC(r)
        scatter(axCR,robC(r),r,(markerSize+3)^2, ...
            'MarkerFaceColor','none', ...
            'MarkerEdgeColor','k', ...
            'LineWidth',1.35, ...
            'HandleVisibility','off');
    end

    text(axCR,1.022,r,sprintf('%.2f',robC(r)), ...
        'HorizontalAlignment','left', ...
        'VerticalAlignment','middle', ...
        'FontName','Arial', ...
        'FontSize',10.5, ...
        'Color',SUBINK, ...
        'Clipping','off');
end

hOther = plot(axCR,nan,nan,'o', ...
    'MarkerSize',8.7, ...
    'MarkerFaceColor',OTHER, ...
    'MarkerEdgeColor','k', ...
    'LineWidth',0.95);

hUnan = plot(axCR,nan,nan,'o', ...
    'MarkerSize',10.0, ...
    'MarkerFaceColor',UNAN, ...
    'MarkerEdgeColor','k', ...
    'LineWidth',0.95);

hBest = plot(axCR,nan,nan,'o', ...
    'MarkerSize',11.5, ...
    'MarkerFaceColor',BEST, ...
    'MarkerEdgeColor','k', ...
    'LineWidth',1.0);

