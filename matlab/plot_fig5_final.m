    'String','b', ...
    'EdgeColor','none', ...
    'FontName','Arial', ...
    'FontSize',30, ...
    'FontWeight','bold', ...
    'Color','k');

axB = axes(figB,'Position',[0.235 0.085 0.720 0.835]);
hold(axB,'on');

for r = 1:nPairs

    if robustness_B(r,3) >= 1-1e-12
        patch(axB,[0.495 1.005 1.005 0.495], ...
            [r-0.42 r-0.42 r+0.42 r+0.42], ...
            [0.91 0.96 0.96], ...
            'FaceAlpha',0.9, ...
            'EdgeColor','none', ...
            'HandleVisibility','off');
    end
end

xline(axB,0.50,':','Color',[0.76 0.76 0.76],'LineWidth',1.0);
xline(axB,1.00,'-','Color',[0.40 0.40 0.40],'LineWidth',1.1);

for r = 1:nPairs

    rr = robustness_B(r,:);
    rmin = min(rr);
    rmax = max(rr);

    if rr(3) >= 1-1e-12
        barCol = TEAL;
    elseif rr(3) >= 0.90
        barCol = NAVY;
    elseif rr(3) >= 0.75
        barCol = SLATE;
    else
        barCol = [0.63 0.69 0.74];
    end

    plot(axB,[0.50 1.00],[r r],'-', ...
        'Color',[0.88 0.89 0.90], ...
        'LineWidth',7.4, ...
        'Clipping','off');

    plot(axB,[rmin rmax],[r r],'-', ...
        'Color',barCol, ...
        'LineWidth',7.4, ...
        'Clipping','off');

    plot(axB,[rmin rmax],[r r],'-', ...
        'Color','k', ...
        'LineWidth',1.0, ...
        'Clipping','off');

    plot(axB,rr(1),r,'o', ...
        'MarkerSize',7.0, ...
        'MarkerFaceColor','w', ...
        'MarkerEdgeColor','k', ...
        'LineWidth',1.0);

    plot(axB,rr(2),r,'d', ...
        'MarkerSize',7.8, ...
        'MarkerFaceColor',HARM, ...
        'MarkerEdgeColor','k', ...
        'LineWidth',0.9);

    plot(axB,rr(3),r,'o', ...
        'MarkerSize',8.8, ...
        'MarkerFaceColor',barCol, ...
        'MarkerEdgeColor','k', ...
        'LineWidth',0.9);
end

set(axB, ...
    'YDir','reverse', ...
    'YLim',[0.35 nPairs+0.65], ...
    'YTick',1:nPairs, ...
    'YTickLabel',pairLabels_B, ...
    'XLim',[0.49 1.015], ...
    'XTick',[0.50 0.60 0.70 0.80 0.90 1.00], ...
    'FontName','Arial', ...
    'FontSize',11.0, ...
    'LineWidth',1.0, ...
    'TickDir','out', ...
    'Box','off', ...
    'XColor',INK, ...
    'YColor',INK);

xlabel(axB,'Ranking consistency across admissible solutions', ...
    'FontSize',19.0, ...
    'Color',INK);

annotation(figB,'textbox',[0.335 0.932 0.52 0.030], ...
    'String',sprintf('Unanimously ordered pairs:  N=30, %d/36     N=50, %d/36     N=100, %d/36', ...
    unanimousCounts(1),unanimousCounts(2),unanimousCounts(3)), ...
    'EdgeColor','none', ...
    'HorizontalAlignment','center', ...
    'FontName','Arial', ...
    'FontSize',14.0, ...
    'Color',SUBINK);

hTrack = plot(axB,nan,nan,'-','Color',[0.65 0.72 0.76],'LineWidth',7.4);
h30 = plot(axB,nan,nan,'o', ...
    'MarkerSize',7.0, ...
    'MarkerFaceColor','w', ...
    'MarkerEdgeColor','k', ...
    'LineWidth',1.0);
h50 = plot(axB,nan,nan,'d', ...
    'MarkerSize',7.8, ...
    'MarkerFaceColor',HARM, ...
    'MarkerEdgeColor','k', ...
    'LineWidth',0.9);
h100 = plot(axB,nan,nan,'o', ...
    'MarkerSize',8.8, ...
    'MarkerFaceColor',NAVY, ...
    'MarkerEdgeColor','k', ...
    'LineWidth',0.9);

lgB = legend(axB,[hTrack h30 h50 h100], ...
    {'Range across N=30,50,100','N=30','N=50','N=100'}, ...
    'NumColumns',4, ...
    'Box','off', ...
    'FontName','Arial', ...
    'FontSize',12.0);

lgB.Position = [0.415 0.952 0.42 0.028];

save_panel_local(figB,output_dir,'Fig5_b');

%% =========================================================================
% PANEL c — effect separation + N=100 ranking consistency
%             (integrated alternative lollipop design)
% =========================================================================
rob100 = robustness(:,3);

idxHHLL = find(strcmp(pairLabels,'HH-LL'),1);

isHHLL = false(nPairs,1);
if ~isempty(idxHHLL)
    isHHLL(idxHHLL) = true;
end

isUnanimous100 = rob100 >= 1-1e-12;

% Sort rows by effect separation, largest first.
sortMatC = [-medianAbsEffect100(:), -rob100(:)];
[~,ordC] = sortrows(sortMatC,[1 2]);

pairLabelsC = pairLabels(ordC);
robC = rob100(ordC);
medAbsC = medianAbsEffect100(ordC);
isHHC = isHHLL(ordC);
isUniC = isUnanimous100(ordC);

positiveX = medAbsC(isfinite(medAbsC) & medAbsC > 0);

if isempty(positiveX)
    positiveX = 1;
end

xminC = max(min(positiveX)/1.8,1e-3);
xmaxC = max(positiveX)*1.55;

xEffect = medAbsC;
xEffect(~isfinite(xEffect) | xEffect <= 0) = xminC;

rowC = (1:nPairs)';

figC = figure( ...
    'Color','w', ...
    'Units','pixels', ...
    'Position',[100 35 1420 1120], ...
    'Name','Fig5_c', ...
    'NumberTitle','off');

set(figC,'Renderer','painters');

annotation(figC,'textbox',[0.018 0.952 0.035 0.035], ...
    'String','c', ...
    'EdgeColor','none', ...
    'FontName','Arial', ...
    'FontSize',30, ...
    'FontWeight','bold', ...
    'Color','k');

leftPosC  = [0.175 0.105 0.350 0.785];
rightPosC = [0.610 0.105 0.255 0.785];

% LEFT: effect separation
axCL = axes(figC,'Position',leftPosC);
hold(axCL,'on');

set(axCL, ...
    'XScale','log', ...
    'XLim',[xminC xmaxC], ...
    'YDir','reverse', ...
    'YLim',[0.35 nPairs+0.65], ...
    'YTick',rowC, ...
    'YTickLabel',pairLabelsC, ...
    'FontName','Arial', ...
    'FontSize',11.0, ...
    'LineWidth',1.0, ...
    'TickDir','out', ...
    'Box','off', ...
    'XColor',INK, ...
    'YColor',INK);

xlabel(axCL,'Absolute median pairwise effect difference (10^3 reported cases)', ...
    'FontSize',18, ...
    'Color',INK);

for r = 1:nPairs

    line(axCL,[xminC xmaxC],[r r], ...
        'Color',[0.92 0.93 0.94], ...
        'LineWidth',0.60, ...
        'HandleVisibility','off');

    if isHHC(r)
        cNow = BEST;
        lineW = 6.8;
        markerSize = 11.5;
    elseif isUniC(r)
        cNow = UNAN;
        lineW = 5.8;
        markerSize = 10.0;
    else
        cNow = OTHER;
        lineW = 4.8;
        markerSize = 8.7;
    end

    line(axCL,[xminC xEffect(r)],[r r], ...
        'Color',lighten_local(cNow,0.55), ...
        'LineWidth',lineW, ...
        'HandleVisibility','off');

    line(axCL,[xminC xEffect(r)],[r r], ...
        'Color','k', ...
        'LineWidth',0.85, ...
        'HandleVisibility','off');

    scatter(axCL,xEffect(r),r,markerSize^2, ...
        'MarkerFaceColor',cNow, ...
        'MarkerEdgeColor','k', ...
        'LineWidth',0.95, ...
        'HandleVisibility','off');

    if isHHC(r)
        scatter(axCL,xEffect(r),r,(markerSize+3)^2, ...
            'MarkerFaceColor','none', ...
            'MarkerEdgeColor','k', ...
            'LineWidth',1.35, ...
            'HandleVisibility','off');
    end
end

% RIGHT: ranking consistency
axCR = axes(figC,'Position',rightPosC);
hold(axCR,'on');

set(axCR, ...
    'XLim',[0.50 1.015], ...
