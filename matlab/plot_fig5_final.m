function R = pairwise_total_reported_local(values)

nStrategies = size(values,2);

E = squeeze(values(:,:,1,5));

R = zeros(nStrategies,nStrategies);

for i = 1:nStrategies
    for j = 1:nStrategies

        if i == j
            R(i,j) = 0;
        else
            R(i,j) = mean(E(:,i) > E(:,j));
        end
    end
end
end


function n = count_unanimous_pairs_local(R)

nStrategies = size(R,1);

n = 0;

for i = 1:(nStrategies-1)
    for j = (i+1):nStrategies

        p = R(i,j);

        if p <= 1e-12 || p >= 1-1e-12
            n = n + 1;
        end
    end
end
end


function labels = unanimous_pair_labels_local(R,strategyNames)

nStrategies = size(R,1);

labels = {};

for i = 1:(nStrategies-1)
    for j = (i+1):nStrategies

        p = R(i,j);

        if p <= 1e-12 || p >= 1-1e-12
            labels{end+1} = [strategyNames{i} '-' strategyNames{j}]; %#ok<AGROW>
        end
    end
end
end


function save_panel_local(fig,output_dir,name)

figFile = fullfile(output_dir,[name '.fig']);
pngFile = fullfile(output_dir,[name '.png']);

savefig(fig,figFile);

if exist(pngFile,'file')
    try
        delete(pngFile);
    catch
        pngFile = fullfile(output_dir, ...
            [name '_' datestr(now,'yyyymmdd_HHMMSS') '.png']);
    end
end

try
    exportgraphics(fig,pngFile, ...
        'Resolution',600, ...
        'BackgroundColor','white');
catch ME
    warning('exportgraphics failed for %s: %s. Falling back to print().', ...
        name,ME.message);

    print(fig,pngFile,'-dpng','-r600');
end
end


function c = darken_local(c0,amount)

amount = max(0,min(1,amount));
c = c0.*(1-amount);
c = min(max(c,0),1);
end


function c = lighten_local(c0,amount)

amount = max(0,min(1,amount));
c = c0 + (1-c0).*amount;
c = min(max(c,0),1);
end
